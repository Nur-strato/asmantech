export const SERVICE_IDS = SERVICES.map((s) => s.id);

function formatService(s: (typeof SERVICES)[number]): string {
    return [
        `### ${s.title} (id: ${s.id})`,
        s.description,
        s.details,
        "Что входит:",
        ...s.deliverables.map((d) => `- ${d}`),
        `Сроки: ${s.timeline}`,
    ].join("\n");
}

export function buildKnowledgeBase(): string {
    return [
        "## О компании",
        COMPANY_INFO,
        "## Основные услуги",
        ...SERVICES.map(formatService),
    ].join("\n\n");
}

export function serviceTitle(id: string): string | undefined {
    return SERVICES.find((s) => s.id === id)?.title;
}

